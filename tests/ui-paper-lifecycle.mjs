// Real local Flask API + PostgreSQL. Only market books and old history are synthetic.
import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const api = 'http://127.0.0.1:5587';
const out = '/private/tmp/arbinator-ui-paper-lifecycle';
await mkdir(out, {recursive: true});
const browser = await chromium.launch({headless:true, executablePath: process.env.CHROME_PATH});
const context = await browser.newContext({viewport: {width:1440,height:1000}});
const page = await context.newPage();
const errors = [], observations = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
async function read(path) {
  const response = await context.request.get(api + path);
  assert.equal(response.status(), 200, path);
  return response.json();
}
async function tick(price, extra={}) {
  const response = await context.request.post(api + '/__fixture__/book', {data:{price,...extra}});
  assert.equal(response.status(), 200);
  return (await response.json()).obj;
}
async function route(path) {
  await page.goto('http://127.0.0.1:5186' + path);
  await page.getByRole('heading', {level:1}).waitFor();
  await page.getByRole('button', {name:'Refresh',exact:true}).click();
  await page.waitForTimeout(400);
}
async function clickApi(name, suffix) {
  const response = page.waitForResponse(r => r.url().endsWith(suffix) && r.request().method() === 'POST');
  await page.getByRole('button', {name,exact:true}).click();
  const result = await (await response).json();
  assert.equal(result.success, true, JSON.stringify(result));
  await page.waitForTimeout(300);
  return result.obj;
}
try {
  const identity = await read('/__fixture__/identity');
  assert.equal(identity.live_hard_disabled, 'true');
  assert.equal(identity.database, 'arbinator_safety_test_ui_lifecycle');
  await route('/bot-settings');
  const first = await clickApi('New paper session', '/paper-sessions');
  const session1 = first.config.paper_session_id;
  assert.ok(session1);
  assert.equal((await read('/api/orderbook-recovery/metrics')).obj.total_trades, 0);
  const ttl = Number((await read('/api/orderbook-recovery/config')).obj.pending_entry_ttl_seconds) === 20 ? 21 : 20;
  await page.getByLabel('Pending entry TTL seconds', {exact:true}).fill(String(ttl));
  await page.getByLabel('Block new entries', {exact:true}).uncheck();
  await page.getByRole('button',{name:'Review changes',exact:true}).click();
  const patch = page.waitForResponse(r => r.url().endsWith('/config') && r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  assert.equal((await (await patch).json()).success, true);
  assert.equal((await read('/api/orderbook-recovery/config')).obj.pending_entry_ttl_seconds,ttl);
  await route('/orderbook-recovery');
  await clickApi('Start paper entries','/start-paper');
  await tick(100);
  await page.waitForTimeout(50);
  let state = await tick(100.02);
  assert.ok(state.pending_order, JSON.stringify(state));
  const cancelledId = state.pending_order.id;
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByText('Pending paper entry', {exact:false}).waitFor();
  await page.screenshot({path:out+'/pending.png',fullPage:true});
  await clickApi('Pause new entries','/stop');
  state = await tick(100.03);
  assert.equal(state.pending_order,null);
  assert.equal(state.open_position,null);
  let trades = (await read('/api/orderbook-recovery/trades')).obj;
  assert.equal(trades.find(t=>t.id===cancelledId).result,'cancelled');
  observations.push({check:'pause_cancels_pending',trade:cancelledId});
  await clickApi('Start paper entries','/start-paper');
  state = await tick(100.04);
  assert.ok(state.pending_order);
  await page.waitForTimeout(1600);
  state = await tick(100.05);
  assert.ok(state.open_position,JSON.stringify(state));
  const openId=state.open_position.id;
  await clickApi('Pause new entries','/stop');
  state = await tick(100.06);
  assert.equal(state.enabled,false);
  assert.equal(state.open_position.id,openId);
  await route('/positions');
  await page.screenshot({path:out+'/open-paused.png',fullPage:true});
  const requestedAt = Date.now();
  const requested = await clickApi('Close Position',`/positions/${openId}/close-manual`);
  assert.equal(requested.closed_at,null);
  assert.equal(requested.paper_exit_status,'pending_fixed_latency');
  state=await tick(100.07);
  assert.ok(state.open_position,'close must wait fixed latency');
  await page.waitForTimeout(1600);
  state=await tick(100.08,{depth:.000001,spread:2});
  assert.equal(state.open_position.id,openId);
  assert.match(state.open_position.paper_exit_status,/unresolved/);
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByText('Paper exit status:',{exact:false}).waitFor();
  await page.screenshot({path:out+'/unresolved.png',fullPage:true});
  state=await tick(100.09,{spread:2});
  assert.equal(state.open_position,null,'wide spread must not block manual close');
  trades=(await read('/api/orderbook-recovery/trades')).obj;
  const closed=trades.find(t=>t.id===openId);
  assert.ok(closed.closed_at);
  assert.equal(closed.reason_close,'manual_close');
  assert.equal(closed.exit_price,99.09);
  const metrics=(await read('/api/orderbook-recovery/metrics')).obj;
  assert.equal(metrics.total_trades,1);
  assert.ok(Math.abs(metrics.net_pnl-closed.net_pnl)<1e-9);
  observations.push({check:'latency_depth_wide_spread_exit',elapsed_ms:Date.now()-requestedAt,trade:closed,metrics});
  await route('/bot-settings');
  const second=await clickApi('New paper session','/paper-sessions');
  assert.notEqual(second.config.paper_session_id,session1);
  const clean=(await read('/api/orderbook-recovery/metrics')).obj;
  assert.equal(clean.total_trades,0);
  assert.equal(clean.net_pnl,0);
  assert.equal((await read('/api/orderbook-recovery/trades')).obj.length,trades.length,'history must survive');
  await route('/positions');
  await page.getByText(`#${openId}`,{exact:true}).first().waitFor();
  await page.getByText('Current paper session only. Simulated PnL, not confirmed profit.',{exact:true}).waitFor();
  await page.screenshot({path:out+'/preserved-history.png',fullPage:true});
  observations.push({check:'session_isolation_history_preserved',session1,session2:second.config.paper_session_id,metrics:clean});
  // Protective SL remains active after Pause, independently of entry spread filters.
  await route('/orderbook-recovery');
  await clickApi('Start paper entries','/start-paper');
  await tick(100.2);
  state=await tick(100.3);
  assert.ok(state.pending_order);
  await page.waitForTimeout(1600);
  state=await tick(100.4);
  assert.ok(state.open_position);
  const stopId=state.open_position.id;
  await clickApi('Pause new entries','/stop');
  state=await tick(94,{spread:2});
  assert.equal(state.enabled,false);
  assert.equal(state.open_position.paper_exit_status,'pending_fixed_latency');
  await page.waitForTimeout(1600);
  state=await tick(93.9,{spread:2});
  assert.equal(state.open_position,null);
  const stopped=(await read('/api/orderbook-recovery/trades')).obj.find(t=>t.id===stopId);
  assert.equal(stopped.reason_close,'stop_loss');
  observations.push({check:'paused_protective_stop_wide_spread',trade:stopped});
  await route('/positions');
  await page.screenshot({path:out+'/paused-stop-closed.png',fullPage:true});
  await route('/bot-settings');
  await clickApi('New paper session','/paper-sessions');
  await page.getByLabel('Pending entry TTL seconds',{exact:true}).fill('0.5');
  await page.getByRole('button',{name:'Review changes',exact:true}).click();
  const ttlSave=page.waitForResponse(r=>r.url().endsWith('/config') && r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  assert.equal((await (await ttlSave).json()).success,true);
  await route('/orderbook-recovery');
  await clickApi('Start paper entries','/start-paper');
  await tick(100.5);
  state=await tick(100.6);
  assert.ok(state.pending_order);
  const expiredId=state.pending_order.id;
  await page.waitForTimeout(700);
  state=await tick(100.7);
  assert.equal(state.pending_order,null);
  assert.equal(state.open_position,null);
  const expired=(await read('/api/orderbook-recovery/trades')).obj.find(t=>t.id===expiredId);
  assert.equal(expired.reason_close,'pending_entry_expired');
  assert.equal((await read('/api/orderbook-recovery/metrics')).obj.total_trades,0);
  observations.push({check:'ui_saved_ttl_expires_without_fill',trade:expired});
  await clickApi('Pause new entries','/stop');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:out+'/mobile.png',fullPage:true});
  const legacyResponse = await context.request.post(api + '/__fixture__/legacy-position');
  assert.equal(legacyResponse.status(),200);
  const legacyId = (await legacyResponse.json()).id;
  await route('/positions');
  await clickApi('Close Position',`/positions/${legacyId}/close-manual`);
  assert.equal((await read('/api/orderbook-recovery/state')).obj.open_position.closed_at,null);
  await clickApi('Close Position',`/positions/${legacyId}/close-manual`);
  await tick(99);
  const retry = await context.request.post(api + `/api/orderbook-recovery/positions/${legacyId}/close-manual`,{data:{reason:'manual_close'}});
  assert.equal(retry.status(),200);
  assert.ok((await retry.json()).obj.closed_at);
  assert.equal((await read('/api/orderbook-recovery/state')).obj.enabled,false);
  observations.push({check:'legacy_short_paused_missing_book_repeated_close',trade:legacyId});
  assert.deepEqual(errors,[]);
  await writeFile(out+'/results.json',JSON.stringify({fixture:true,identity,observations,errors},null,2));
  console.log(JSON.stringify({passed:true,screenshots:out,errors,observations:observations.length}));
} catch(error) {
  await page.screenshot({path:out+'/failure.png',fullPage:true});
  console.error((await page.locator('body').innerText()).slice(0,6000));
  throw error;
} finally {await browser.close();}
